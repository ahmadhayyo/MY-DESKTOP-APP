@cl.on_chat_start
async def on_chat_start() -> None:
    """Generate or restore a session thread_id and set up model selector."""
    global GRAPH
    GRAPH = _get_graph()

    # ── Start the background scheduler loop (once per session) ─────────────
    _start_scheduler_loop()

