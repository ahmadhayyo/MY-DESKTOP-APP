# ── DeepSeek DSML tag strippers ───────────────────────────────────────────────
# DeepSeek sometimes encodes tool calls as <｜｜DSML｜｜tag>...</｜｜DSML｜｜tag>
# We strip all of these so they never appear in the UI.
_DSML_MARKER   = "｜｜DSML｜｜"        # ｜｜DSML｜｜  (full-width pipes)
_DSML_OPEN     = "<"  + _DSML_MARKER                   # <｜｜DSML｜｜
_DSML_CLOSE    = "</" + _DSML_MARKER                   # </｜｜DSML｜｜
# Matches a complete DSML block: <｜｜DSML｜｜tag>...content...</｜｜DSML｜｜tag>
_DSML_BLOCK_RE = re.compile(
    re.escape(_DSML_OPEN) + r"[^>]*>.*?" + re.escape(_DSML_CLOSE) + r"[^>]*>",
    re.DOTALL,
)
# Matches any standalone DSML tag (open or close)
_DSML_TAG_RE   = re.compile(re.escape(_DSML_OPEN) + r"[^>]*/?>|" + re.escape(_DSML_CLOSE) + r"[^>]*/?>")
# Matches a partial/truncated DSML tag at end of streaming chunk
_DSML_FRAG_RE  = re.compile(re.escape(_DSML_OPEN) + r".*|" + re.escape(_DSML_CLOSE) + r".*")


def _strip_dsml(text: str) -> str:
    """Remove all DeepSeek DSML tag artefacts from streaming text.

    Applies block removal in a loop to handle nested tags, then strips any
    remaining open/close tags and partial fragments.
    """
    # Loop until no more DSML blocks found (handles nested blocks)
    prev = None
    while prev != text:
        prev = text
        text = _DSML_BLOCK_RE.sub('', text)
    # Remove any leftover open/close tags
    text = _DSML_TAG_RE.sub('', text)
    # Remove any partial tag fragments (e.g. chunk cut-off mid-tag)
    text = _DSML_FRAG_RE.sub('', text)
    return text


def _filter_internal_tokens(text: str) -> str:
    """Strip internal control tokens and DSML artefacts before showing to user."""
    if not text:
        return text
    # 1. Strip DSML blocks first (may span multiple lines)
    text = _strip_dsml(text)
    # 2. Filter line-by-line for internal markers
    lines = text.split("\n")
    cleaned = []
    for line in lines:
        if any(marker in line for marker in _INTERNAL_MARKERS):
            continue
        cleaned.append(line)
    result = "\n".join(cleaned).strip()
    # 3. Collapse multiple blank lines
    while "\n\n\n" in result:
        result = result.replace("\n\n\n", "\n\n")
    return result


def _extract_text_chunk(chunk: AIMessageChunk) -> str:
    content = chunk.content
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "".join(
            block.get("text", "")
            for block in content
            if isinstance(block, dict) and block.get("type") == "text"
        )
    return ""


def _parse_plan_steps(text: str) -> list[str]:
    """Extract numbered plan steps from planner output."""
    steps = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and (re.match(r'^\d+[\.\)]\s', stripped) or stripped.startswith("•")):
            steps.append(stripped)
    return steps


async def _run_graph(input_or_command, config: dict) -> None:
    """Stream a single graph invocation with clean Claude-like display.

    Architecture
    ────────────
    • Planner   → collapsible "🧠 يخطط..." step  (NEVER in main message)
    • Worker    → collapsible "⚙️ خطوة N" steps  (NEVER in main message)
    • Reviewer  → ONLY the final TASK_COMPLETE/FAILED answer → main message
    • CONVERSATIONAL_ONLY → streams directly to main message (no steps)

    This keeps the main message bubble clean: the user sees ONLY the final
    answer, exactly like Claude's response style. Internal reasoning and
    tool calls stay inside collapsible steps.

    DSML filtering
    ──────────────
    DeepSeek leaks <｜｜DSML｜｜...> tags into streaming chunks.
    _strip_dsml() is applied to every chunk before routing.
    """
    global GRAPH
    if GRAPH is None:
        GRAPH = _get_graph()

    # ── Main response bubble (starts empty — only filled by reviewer/conversational)
    response_msg = cl.Message(content="")
    await response_msg.send()

    # ── Step handles ─────────────────────────────────────────────────────────
    active_step:       cl.Step | None = None   # top-level phase (plan/execute/review)
    worker_step:       cl.Step | None = None   # current tool sub-step
    worker_step_count: int = 0
    current_tool_name: str = ""                # tool owning the open worker_step
    plan_steps:        list[str] = []
    planner_buf:       list[str] = []   # accumulates planner output for plan parsing
    reviewer_buf:      list[str] = []   # filtered reviewer text → step display
    reviewer_iter_raw: list[str] = []   # RAW reviewer text for current LLM call (unfiltered)
    reviewer_final_text: str = ""       # raw text of the TASK_COMPLETE/FAILED reviewer call
    final_text_buf:    list[str] = []   # what gets read aloud in voice mode

    current_node:     str | None = None
    is_conversational: bool = False
    _nodes_with_chunks: set[str] = set()
    _line_buf:        list[str] = []   # partial-line buffer for token-level filtering
    # Set parent_id immediately after send() so ALL Steps nest under this bubble.
    # Do NOT do lazy init inside the loop — response_msg.id is available right now.
    _parent_id: str | None = response_msg.id

    # ── Live "Task progress" panel (mirrors the reference dropdown) ───────────
    # A dedicated collapsible step that shows the agent's live todo checklist
    # with completed items struck through. Lazily created on the first non-empty
    # board so conversational replies don't show an empty panel.
    task_progress_step: cl.Step | None = None
    _last_board: str = ""

    async def _refresh_task_progress() -> None:
        nonlocal task_progress_step, _last_board
        try:
            from core import todo as _todo
            board = _todo.render_markdown(_todo.active_task())
        except Exception:
            return
        if not board or board == _last_board:
            return
        _last_board = board
        try:
            done, total = 0, 0
            try:
                from core import todo as _todo2
                done, total = _todo2.progress(_todo2.active_task())
            except Exception:
                pass
            if task_progress_step is None:
                task_progress_step = cl.Step(
                    name=f"📋 قائمة المهام | Task progress ({done}/{total})",
                    type="run", parent_id=_parent_id,
                )
                await task_progress_step.__aenter__()
            else:
                task_progress_step.name = f"📋 قائمة المهام | Task progress ({done}/{total})"
            task_progress_step.output = board
            await task_progress_step.update()
        except Exception:
            pass

    # ─────────────────────────────────────────────────────────────────────────
    # Phase headers resolve from "in progress" to a completed summary when the
    # phase ends, so a finished run reads as a log of what happened instead of a
    # column of spinners frozen mid-sentence.
    _PHASE_RUNNING = {
        "planner":  "🧠 يفكّر ويخطّط…",
        "worker":   "⚡ ينفّذ…",
        "reviewer": "🔍 يراجع…",
    }

    def _phase_done_label(node: str) -> str:
        if node == "planner":
            return f"🧠 خطّط ({len(plan_steps)} خطوة)" if plan_steps else "🧠 خطّط"
        if node == "worker":
            return f"⚡ نفّذ ({worker_step_count} أداة)" if worker_step_count else "⚡ نفّذ"
        if node == "reviewer":
            return "🔍 راجع"
        return node

    async def _close_worker_step() -> None:
        nonlocal worker_step
        if worker_step:
            await worker_step.__aexit__(None, None, None)
            worker_step = None

    async def _close_active_step() -> None:
        nonlocal active_step
        if active_step:
            if current_node:
                active_step.name = _phase_done_label(current_node)
            await active_step.__aexit__(None, None, None)
            active_step = None

    def _clean_plan_label(raw: str) -> str:
        """Remove leading number and tool-call parentheses for clean step labels."""
        s = re.sub(r'^\d+[\.\)]\s*', '', raw).strip()
        s = re.sub(r'\(.*?\)', '', s).strip()   # remove (url='...') etc.
        s = re.sub(r'\→.*$', '', s).strip()     # remove → description
        return s or raw

    # ── Tool invocation rendering ────────────────────────────────────────────
    # Args stream in as partial JSON fragments across many chunks, so we buffer
    # them per tool-call and re-label the step once the JSON parses. This is what
    # turns "🔧 read_file" into "🔧 read_file(path=config.py)" — i.e. *what* ran,
    # not just which tool.
    tool_args_buf: dict[str, list[str]] = {}

    def _fmt_tool_label(tool_name: str, args_json: str) -> str:
        """Render an invocation label: tool(key=value, …)."""
        try:
            args = json.loads(args_json) if args_json.strip() else {}
        except Exception:
            return f"🔧 {tool_name}"
        if not isinstance(args, dict) or not args:
            return f"🔧 {tool_name}()"
        parts = []
        for k, v in list(args.items())[:3]:
            s = str(v).replace("\n", " ").strip()
            if len(s) > 44:
                s = s[:41] + "…"
            parts.append(f"{k}={s}")
        more = ", …" if len(args) > 3 else ""
        return f"🔧 {tool_name}({', '.join(parts)}{more})"

    # Failure markers scanned for in the head of a tool result. Tools here report
    # errors as ordinary return values rather than raising, and rarely put the
    # marker first (e.g. list_dir returns a path line, THEN "Permission denied"),
    # so a startswith() check silently labels real failures as successes.
    # Word boundaries keep "errors" from matching inside unrelated words.
    _ERR_RE = re.compile(
        r"❌|traceback \(most recent call last\)|permission denied|access is denied"
        r"|winerror|errno|no such file|not found"
        r"|\b(?:error|errors|exception|failed|failure|denied)\b"
        r"|فشل|تعذّر|تعذر|خطأ|غير موجود|مرفوض|رُفض",
        re.IGNORECASE,
    )
    # "0 errors" / "no failures" are success reports, not failures — strip them
    # before scanning so a clean test run isn't flagged red.
    _ERR_NEGATED_RE = re.compile(
        r"\b(?:0|no|zero)\s+(?:errors?|failures?|exceptions?)\b", re.IGNORECASE
    )

    def _summarize_tool_result(result: str) -> tuple[str, bool]:
        """Return (one-line summary, ok) so the step header shows the outcome."""
        stripped = result.strip()
        head = _ERR_NEGATED_RE.sub("", stripped[:400])
        ok = not _ERR_RE.search(head)
        if not stripped:
            return "بلا مخرجات", ok
        n_lines = stripped.count("\n") + 1
        size = len(stripped)
        size_txt = f"{size / 1024:.1f} ك.ب" if size >= 1024 else f"{size} حرفًا"
        return (f"{n_lines} سطرًا · {size_txt}" if n_lines > 1 else size_txt), ok

    async def _flush_line_buf_to(dest: str) -> None:
        """Flush accumulated partial-line buffer to the given destination."""
        if not _line_buf:
            return
        raw = "".join(_line_buf)
        _line_buf.clear()

        # Reviewer path: always track RAW (for verdict detection) separately
        if dest == "reviewer_buf":
            reviewer_iter_raw.append(raw)          # ← RAW, before any filtering
            filtered = _filter_internal_tokens(raw)
            if filtered.strip():
                reviewer_buf.append(filtered)       # filtered → step display
                if active_step:
                    await active_step.stream_token(filtered)
            return

        filtered = _filter_internal_tokens(raw)
        if not filtered.strip():
            return
        if dest == "main":
            await response_msg.stream_token(filtered)
            final_text_buf.append(filtered)
        elif dest == "active_step" and active_step:
            await active_step.stream_token(filtered)
        elif dest == "worker_step" and worker_step:
            await worker_step.stream_token(filtered)
        # "discard" → just drop (worker reasoning before first tool call)

    # ─────────────────────────────────────────────────────────────────────────
    try:
        async for msg_chunk, metadata in GRAPH.astream(
            input_or_command, config=config, stream_mode="messages"
        ):
            node = metadata.get("langgraph_node", "")

            # Keep the live task-progress panel fresh as work proceeds.
            await _refresh_task_progress()

            # ── Node transition ───────────────────────────────────────────
            if node and node != current_node:
                # Flush whatever was left in the line buffer for the OLD node
                if current_node == "planner":
                    if is_conversational:
                        await _flush_line_buf_to("main")
                    else:
                        await _flush_line_buf_to("active_step")
                elif current_node == "worker":
                    await _flush_line_buf_to("worker_step")
                elif current_node == "reviewer":
                    await _flush_line_buf_to("reviewer_buf")
                    # This transition means the reviewer said CONTINUE (graph is going to worker).
                    # Discard this iteration — we only display the TASK_COMPLETE/FAILED one.
                    reviewer_iter_raw.clear()
                else:
                    _line_buf.clear()

                # Leaving planner → handle conversational vs task
                if current_node == "planner":
                    if is_conversational:
                        # Push ALL planner text to the main response bubble.
                        # Earlier chunks may have gone to active_step before
                        # CONVERSATIONAL_ONLY was detected — replay them now.
                        full_text = "".join(planner_buf)
                        clean = _filter_internal_tokens(full_text).strip()
                        if clean and not final_text_buf:
                            await response_msg.stream_token(clean)
                            final_text_buf.append(clean)
                    else:
                        full = "".join(planner_buf)
                        plan_steps = _parse_plan_steps(full)
                        if active_step and plan_steps:
                            # Append the parsed plan *below* the streamed reasoning
                            # rather than replacing it — the thinking is now visible
                            # live, and overwriting it would wipe what the user just
                            # watched appear.
                            plan_content = "\n\n**📋 الخطوات المخططة:**"
                            for i, s in enumerate(plan_steps, 1):
                                plan_content += f"\n{i}. {_clean_plan_label(s)}"
                            await active_step.stream_token(plan_content)

                # Leaving worker → close its sub-step
                if current_node == "worker":
                    await _close_worker_step()

                # Close previous top-level phase step
                await _close_active_step()

                # Open new top-level phase step nested under response_msg
                if node in _PHASE_RUNNING:
                    active_step = cl.Step(name=_PHASE_RUNNING[node], type="run",
                                          parent_id=_parent_id)
                    await active_step.__aenter__()
                    if node == "planner":
                        planner_buf.clear()
                    elif node == "worker":
                        worker_step_count = 0

                current_node = node

            # Skip internal message types
            if isinstance(msg_chunk, (_SysMsg, HumanMessage)):
                continue

            # ── Streaming LLM chunk (AIMessageChunk) ─────────────────────
            if isinstance(msg_chunk, AIMessageChunk):
                _nodes_with_chunks.add(node)
                text = _extract_text_chunk(msg_chunk)

                # Detect tool call → open a worker sub-step
                if node == "worker" and hasattr(msg_chunk, "tool_call_chunks"):
                    for tc in (msg_chunk.tool_call_chunks or []):
                        tool_name = tc.get("name", "")
                        if tool_name:
                            # Flush any worker reasoning into the current step
                            if _line_buf:
                                raw = "".join(_line_buf)
                                _line_buf.clear()
                                filtered = _filter_internal_tokens(raw)
                                if filtered.strip():
                                    if worker_step:
                                        await worker_step.stream_token(filtered)
                                    elif active_step:
                                        await active_step.stream_token(filtered)
                            await _close_worker_step()
                            worker_step_count += 1
                            label = f"🔧 {tool_name}"
                            if worker_step_count <= len(plan_steps):
                                label = f"⚙️ الخطوة {worker_step_count}: {_clean_plan_label(plan_steps[worker_step_count - 1])}"
                            worker_step = cl.Step(name=label, type="tool",
                                                   parent_id=_parent_id)
                            await worker_step.__aenter__()
                            # Start a fresh arg buffer for this invocation.
                            current_tool_name = tool_name
                            tool_args_buf[worker_step.id] = []

                        # Args arrive as partial JSON spread across many chunks.
                        # Buffer them and re-label only once the JSON actually
                        # parses, so the header settles on the real invocation
                        # (path/command/url) instead of flickering through
                        # half-written fragments.
                        frag = tc.get("args") or ""
                        if frag and worker_step and current_tool_name:
                            buf = tool_args_buf.setdefault(worker_step.id, [])
                            buf.append(frag)
                            try:
                                parsed = json.loads("".join(buf))
                            except Exception:
                                parsed = None            # still mid-stream
                            if isinstance(parsed, dict):
                                new_label = _fmt_tool_label(current_tool_name, "".join(buf))
                                if new_label != worker_step.name:
                                    worker_step.name = new_label
                                    await worker_step.update()

                if text:
                    _line_buf.append(text)
                    accumulated = "".join(_line_buf)

                    # Detect CONVERSATIONAL_ONLY as early as possible — even
                    # before a newline arrives. DeepSeek often puts it on the
                    # last line with no trailing \n, so the old newline-gated
                    # check never fires.
                    if node == "planner" and not is_conversational and "CONVERSATIONAL_ONLY" in accumulated:
                        is_conversational = True

                    # Process complete lines only (token-level safety)
                    if "\n" in accumulated:
                        complete, remainder = accumulated.rsplit("\n", 1)
                        _line_buf.clear()
                        if remainder:
                            _line_buf.append(remainder)
                        filtered = _filter_internal_tokens(complete + "\n")
                        if filtered.strip():
                            if node == "planner":
                                planner_buf.append(filtered)
                                if is_conversational:
                                    # Conversational: goes straight to main bubble
                                    await response_msg.stream_token(filtered)
                                    final_text_buf.append(filtered)
                                else:
                                    # Task plan: step output only
                                    if active_step:
                                        await active_step.stream_token(filtered)

                            elif node == "worker":
                                # Worker reasoning/output: step only, never main bubble.
                                # Before the first tool call there is no worker_step
                                # yet, so the reasoning that *leads to* the call would
                                # be dropped — surface it on the phase step instead.
                                if worker_step:
                                    await worker_step.stream_token(filtered)
                                elif active_step:
                                    await active_step.stream_token(filtered)

                            elif node == "reviewer":
                                # RAW text tracked per-iteration for verdict detection
                                reviewer_iter_raw.append(complete + "\n")
                                # Filtered text goes to step display only
                                reviewer_buf.append(filtered)
                                if filtered.strip() and active_step:
                                    await active_step.stream_token(filtered)
                continue

            # ── ToolMessage → show result inside current worker sub-step ──
            if isinstance(msg_chunk, ToolMessage):
                result = (
                    msg_chunk.content
                    if isinstance(msg_chunk.content, str)
                    else str(msg_chunk.content)
                )
                if worker_step and result:
                    summary, ok = _summarize_tool_result(result)
                    # Outcome goes in the header so a collapsed step still tells
                    # you whether it worked; the body keeps the actual output.
                    worker_step.name = f"{'✅' if ok else '❌'} {worker_step.name.lstrip('🔧⚙️ ')} — {summary}"
                    trunc = result[:600] + ("…(مقتطع)" if len(result) > 600 else "")
                    await worker_step.stream_token(f"\n```\n{trunc}\n```")
                    tool_args_buf.pop(worker_step.id, None)
                    await _close_worker_step()
                    current_tool_name = ""
                continue

            # ── Full AIMessage (state-update, not a streaming chunk) ───────
            if isinstance(msg_chunk, AIMessage):
                if node in _nodes_with_chunks:
                    continue   # already streamed above
                text = _extract_text_chunk(msg_chunk)
                if text:
                    if node == "reviewer":
                        reviewer_iter_raw.append(text)   # Track RAW
                        filtered = _filter_internal_tokens(text)
                        if filtered.strip():
                            reviewer_buf.append(filtered)
                            if active_step:
                                await active_step.stream_token(filtered)
                    elif node == "planner":
                        filtered = _filter_internal_tokens(text)
                        if filtered.strip():
                            planner_buf.append(filtered)
                            if is_conversational:
                                await response_msg.stream_token(filtered)
                                final_text_buf.append(filtered)
                continue

    except Exception as exc:
        _exc_str = str(exc).lower()
        _is_conn = (
            type(exc).__name__ in ("ConnectionError", "ConnectError")
            or any(k in _exc_str for k in (
                "10061", "connection refused", "actively refused",
                "connect error", "تعذّر الاتصال", "ollama"))
        )
        _is_auth = any(k in _exc_str for k in (
            "خطأ في المصادقة", "authentication", "401", "unauthorized",
            "invalid api key", "invalid_api_key", "403", "forbidden",
        ))
        # GraphRecursionError = LangGraph step ceiling. With recursion_limit now
        # set well above 2*MAX_ITERATIONS this should be rare, but if a task is
        # genuinely huge, tell the user how to continue instead of a raw trace.
        if type(exc).__name__ == "GraphRecursionError":
            await cl.Message(
                content=(
                    "⏸️ **المهمة طويلة جداً ووصلت حد الخطوات المؤقت.**\n\n"
                    "أنجزت جزءاً كبيراً — اكتب **أكمل** لأتابع من حيث توقفت حتى الانتهاء.\n"
                    "_(لرفع الحد دائماً: `/settings set MAX_ITERATIONS 200`)_"
                )
            ).send()
        elif _is_auth:
            cl.user_session.set("_llm_unreachable", True)
            await cl.Message(content=str(exc)).send()
        elif _is_conn:
            cl.user_session.set("_llm_unreachable", True)
            await cl.Message(
                content=(
                    "🔌 **تعذّر الاتصال بالنموذج.**\n\n"
                    f"{exc}\n\n"
                    "— إن كنت على Ollama: افتح تطبيق Ollama أو شغّل `ollama serve` "
                    "(يحاول الوكيل تشغيله تلقائياً)، وتأكد: `ollama list`.\n"
                    "— أو بدّل لنموذج سحابي جاهز: **/model groq**"
                )
            ).send()
        else:
            await cl.Message(
                content=f"❌ **خطأ في التنفيذ**: {type(exc).__name__}: {exc}"
            ).send()

    finally:
        # ── Flush any remaining partial line ─────────────────────────────
        if _line_buf:
            raw = "".join(_line_buf)
            _line_buf.clear()
            filtered = _filter_internal_tokens(raw)
            if current_node == "reviewer":
                reviewer_iter_raw.append(raw)       # track RAW for verdict check
                if filtered.strip():
                    reviewer_buf.append(filtered)
                    if active_step:
                        # In `finally`, so the stream may already be torn down by
                        # the exception that got us here — never mask it.
                        try:
                            await active_step.stream_token(filtered)
                        except Exception:
                            active_step.output = (active_step.output or "") + filtered
            elif current_node == "planner" and is_conversational:
                if filtered.strip():
                    await response_msg.stream_token(filtered)
                    final_text_buf.append(filtered)

        # ── Commit the last reviewer iteration ───────────────────────────────────
        # Graph ended while current_node == "reviewer" → this IS the final call.
        # (CONTINUE iterations are cleared in the node-transition handler above.)
        if reviewer_iter_raw:
            reviewer_final_text = "".join(reviewer_iter_raw)
            reviewer_iter_raw.clear()

        # ── Build the final reviewer answer ───────────────────────────────────
        # DeepSeek often echoes back the input context (progress_note, system prompt
        # examples) before writing its actual verdict. We eliminate all preamble by
        # slicing from the LAST occurrence of "TASK_COMPLETE" or "FAILED".
        _final_source = reviewer_final_text or "".join(reviewer_buf)
        clean_rev = ""
        _verdict = ""
        if _final_source:
            _tc = _final_source.rfind("TASK_COMPLETE")
            _fl = _final_source.rfind("FAILED")
            _idx = max(_tc, _fl)
            _verdict = "FAILED" if (_fl > _tc) else ("TASK_COMPLETE" if _tc >= 0 else "")
            _verdict_text = _final_source[_idx:] if _idx >= 0 else _final_source
            clean_rev = _filter_internal_tokens(_verdict_text)
            # strip the leading verdict token for clean display
            for _pref in ("TASK_COMPLETE:", "FAILED:", "TASK_COMPLETE", "FAILED"):
                if clean_rev.strip().startswith(_pref):
                    clean_rev = clean_rev.strip()[len(_pref):].strip()
                    break

        await _close_worker_step()
        await _close_active_step()

        # ── Final task-progress refresh + close the panel ────────────────────
        await _refresh_task_progress()
        if task_progress_step is not None:
            try:
                await task_progress_step.__aexit__(None, None, None)
            except Exception:
                pass

        # ── Conversational replay (final safety net) ─────────────────────────
        # Worker/reviewer are pass-through for CONVERSATIONAL_ONLY (no LLM
        # call → no streaming chunks → no node transition detected).  The
        # in-loop replay at the planner→worker transition therefore never
        # fires, leaving the greeting trapped in planner_buf.  Push it to
        # the main bubble now so the user actually sees the response.
        if is_conversational and not final_text_buf and planner_buf:
            _greeting = _filter_internal_tokens("".join(planner_buf)).strip()
            if _greeting:
                response_msg.content = _greeting
                final_text_buf.append(_greeting)

        # ── Place the final report at the BOTTOM of the chat ──────────────────
        # The top bubble (response_msg) holds the collapsible steps. Streaming the
        # report into it would push the answer ABOVE the steps, forcing the user to
        # scroll up. Instead: keep the top bubble as a one-line status, and send the
        # full report as a NEW message so it lands at the bottom, after the steps.
        if clean_rev.strip() and not is_conversational:
            _badge = "✅ **اكتملت المهمة**" if _verdict == "TASK_COMPLETE" else (
                "❌ **تعذّر إكمال المهمة**" if _verdict == "FAILED" else "📋 **النتيجة**")
            response_msg.content = f"{_badge} — التقرير في الأسفل ⬇️"
            await response_msg.update()
            await cl.Message(content=clean_rev).send()   # ← bottom of the chat
            final_text_buf.append(clean_rev)
        else:
            # conversational reply was already streamed into response_msg
            await response_msg.update()

    # ── Voice mode: synthesize and attach audio ──────────────────────────────
    if cl.user_session.get("voice_mode") and final_text_buf:
        try:
            voice_pref = cl.user_session.get("voice_name")
            spoken_text = "".join(final_text_buf)
            audio_bytes = await text_to_speech(spoken_text, voice=voice_pref)
            if audio_bytes:
                audio_elem = cl.Audio(
                    name="reply.mp3",
                    content=audio_bytes,
                    auto_play=True,
                    mime="audio/mpeg",
                )
                await cl.Message(content="🔊", elements=[audio_elem]).send()
        except Exception as exc:
            await cl.Message(content=f"⚠️ TTS error: {exc}").send()


async def _handle_hitl_loop(config: dict) -> None:
    """Handle Human-in-the-Loop interrupts after each graph run."""
    global GRAPH
    if GRAPH is None:
        GRAPH = _get_graph()

    while True:
        state = await GRAPH.aget_state(config)
        if not state.next:
            break
        all_interrupts: list = []
        for task in state.tasks:
            if hasattr(task, "interrupts"):
                all_interrupts.extend(task.interrupts)
        if not all_interrupts:
            break

        interrupt_obj = all_interrupts[0]
        interrupt_data = getattr(interrupt_obj, "value", {})

        if isinstance(interrupt_data, dict):
            interrupt_type = interrupt_data.get("type", "generic")
            interrupt_message = interrupt_data.get("message", str(interrupt_data))
            risky_command = interrupt_data.get("command", "")
        else:
            interrupt_type = "generic"
            interrupt_message = str(interrupt_data)
            risky_command = ""

        # ── Case A: Destructive command ───────────────────────────────────────
        if interrupt_type == "destructive_command":
            res = await cl.AskActionMessage(
                content=(
                    "⚠️ **مطلوب موافقة المستخدم**\n\n"
                    f"الوكيل يريد تنفيذ أمر **قد يكون خطيراً**:\n\n"
                    f"```powershell\n{risky_command}\n```\n\n"
                    "هل تسمح بتنفيذ هذا الأمر؟"
                ),
                actions=[
                    cl.Action(name="approve", payload={"value": "approve"}, label="✅ موافق"),
                    cl.Action(name="deny", payload={"value": "deny"}, label="❌ رفض"),
                ],
                timeout=300,
            ).send()

            user_choice = (
                res.get("payload", {}).get("value", res.get("value", "deny"))
                if res else "deny"
            )
            status = "✅ تم الموافقة." if user_choice == "approve" else "❌ تم الرفض."
            await cl.Message(content=f"{status} جارٍ الاستئناف…").send()
            await _run_graph(Command(resume=user_choice), config)

        # ── Case B: CAPTCHA ───────────────────────────────────────────────────
        elif interrupt_type == "captcha":
            res = await cl.AskActionMessage(
                content=(
                    "🔒 **تم اكتشاف CAPTCHA**\n\n"
                    f"{interrupt_message}\n\n"
                    "يرجى حل الـ CAPTCHA في نافذة المتصفح، ثم اضغط **تم**."
                ),
                actions=[
                    cl.Action(name="done", payload={"value": "done"}, label="✅ تم"),
                    cl.Action(name="skip", payload={"value": "skip"}, label="⏭️ تخطي"),
                ],
                timeout=600,
            ).send()

            user_choice = (
                res.get("payload", {}).get("value", res.get("value", "done"))
                if res else "done"
            )
            await cl.Message(content="▶️ جارٍ الاستئناف بعد حل الـ CAPTCHA…").send()
            await _run_graph(Command(resume=user_choice), config)

        # ── Case C: Generic ───────────────────────────────────────────────────
        else:
            res = await cl.AskUserMessage(
                content=f"⏸️ **الوكيل متوقف مؤقتاً**\n\n{interrupt_message}\n\nاكتب ردك:",
                timeout=300,
            ).send()
            user_response = res.get("output", "continue") if res else "continue"
            await _run_graph(Command(resume=user_response), config)


# ─────────────────────────────────────────────────────────────────────────────
# Autonomous completion — keep working until the task is genuinely done
# ─────────────────────────────────────────────────────────────────────────────
def _verdict_from_state(values: dict) -> str:
    """
    Determine the task verdict from graph state: 'complete' | 'failed' | 'incomplete'.

    The reviewer appends '[Review] <RAW_VERDICT>' to completed_steps every run, and
    RAW_VERDICT starts with TASK_COMPLETE:/FAILED:/CONTINUE:. completed_steps is a
    plain list of strings (fully serializable), so this survives checkpoint reload —
    unlike message .metadata which may not round-trip through SQLite.
    """
    plan = values.get("plan", [])
    if plan and plan[0] == "CONVERSATIONAL_ONLY":
        return "complete"   # a chat reply is a complete "task"
    # The reviewer tags its entry as [Review:TASK_COMPLETE] / [Review:FAILED] /
    # [Review:CONTINUE] (verdict never truncated). Read the most recent one.
    for step in reversed(values.get("completed_steps", [])):
        if isinstance(step, str) and step.startswith("[Review:"):
            tag = step[8:step.find("]")] if "]" in step else ""
            tag = tag.strip().upper()
            if tag == "TASK_COMPLETE":
                return "complete"
            if tag == "FAILED":
                return "failed"
            return "incomplete"   # CONTINUE → not done yet
        # Back-compat: older "[Review] ..." entries without a tag
        if isinstance(step, str) and step.startswith("[Review]"):
            up = step.upper()
            if "TASK_COMPLETE" in up:
                return "complete"
            if "FAILED" in up:
                return "failed"
            return "incomplete"
    return "incomplete"


def _progress_fingerprint(values: dict) -> str:
    """A cheap signal of forward progress, to detect a stalled agent."""
    msgs = values.get("messages", [])
    last_ai = ""
    for m in reversed(msgs):
        if isinstance(m, AIMessage) and not getattr(m, "tool_calls", []):
            _c = m.content
            if not isinstance(_c, str):
                # Gemini/Anthropic return list-of-blocks content — extract text
                _c = "\n".join(
                    (b.get("text", "") if isinstance(b, dict) else str(b))
                    for b in (_c if isinstance(_c, list) else [])
                )
            last_ai = _c[:160]
            break
    return f"{len(msgs)}|{last_ai}"


async def _auto_continue_until_done(config: dict) -> None:
    """
    Keep the agent working autonomously until the task is genuinely complete,
    so the user never has to type "أكمل" mid-task.

    After each graph run we inspect the state. If the reviewer did NOT emit
    TASK_COMPLETE/FAILED (i.e. it stopped on the MAX_ITERATIONS ceiling or a
    loop guard), we automatically resume with a "continue" instruction.

    Stops auto-continuing when ANY of these hold:
      • verdict is TASK_COMPLETE or FAILED (genuinely done), OR
      • a HITL interrupt is pending (needs the user — approval/CAPTCHA), OR
      • two rounds in a row make no forward progress (stuck), OR
      • the hard round cap is reached (runaway safety).

    Disable by setting AUTO_CONTINUE=false in .env.
    """
    global GRAPH
    if GRAPH is None:
        GRAPH = _get_graph()

    # If the LLM was unreachable this turn, do NOT auto-retry — that just spams the
    # same connection error. Clear the flag and bail.
    if cl.user_session.get("_llm_unreachable"):
        cl.user_session.set("_llm_unreachable", False)
        return

    if str(os.getenv("AUTO_CONTINUE", "true")).lower() in ("false", "0", "no", "off"):
        return

    try:
        max_rounds = int(os.getenv("AUTO_CONTINUE_MAX_ROUNDS", "10"))
    except (TypeError, ValueError):
        max_rounds = 10

    last_fp = None
    stalls = 0

    for round_idx in range(max_rounds):
        state = await GRAPH.aget_state(config)

        # HITL interrupt pending → the user must act; never auto-skip it.
        if state.next:
            return

        values = state.values or {}
        verdict = _verdict_from_state(values)
        if verdict in ("complete", "failed"):
            return   # genuinely finished — stop here

        # Stall detection: no forward progress across two rounds.
        fp = _progress_fingerprint(values)
        if fp == last_fp:
            stalls += 1
            if stalls >= 2:
                await cl.Message(
                    content=(
                        "⏸️ توقف الوكيل دون إحراز تقدم جديد. "
                        "قد يحتاج تدخّلاً منك أو إعادة صياغة المهمة."
                    )
                ).send()
                return
        else:
            stalls = 0
        last_fp = fp

        # Auto-resume: re-enter the graph with a continue instruction.
        await cl.Message(
            content=f"🔄 الوكيل يتابع المهمة تلقائياً… (جولة {round_idx + 1})"
        ).send()
        cont_inputs = {
            "messages": [
                HumanMessage(content=(
                    "تابع العمل على نفس المهمة من حيث توقفت بالضبط — لا تبدأ من جديد. "
                    "أكمل كل الخطوات المتبقية حتى تكتمل المهمة بالكامل، ثم اكتب التقرير النهائي. "
                    "إذا لم يتبقَّ شيء فاكتب TASK_COMPLETE مع التقرير."
                ))
            ]
        }
        await _run_graph(cont_inputs, config)
        await _handle_hitl_loop(config)

    # Hard cap reached — extremely long task.
    await cl.Message(
        content=(
            "⏸️ المهمة طويلة جداً ووصلت الحد الأقصى للمتابعة التلقائية. "
            "اكتب **أكمل** لمواصلة العمل."
        )
    ).send()


